import { runTransaction } from 'firebase/firestore';
import { db } from '@/config/firebase';
import { COL } from '@/config/collections';
import type { Order, Payment, PaymentMethod, PrintJob, Settings, Staff } from '@/types/models';
import { AppError } from '@/lib/errors';
import { computeTotals } from '@/lib/pricing';
import { roundTo5Sen } from '@/lib/money';
import { buildReceiptPages } from '@/lib/printLayout';
import { ymd } from '@/lib/time';
import { log } from '@/lib/logger';
import { docRef, fromSnap } from './db';
import { writeAudit } from './audit';

/**
 * PAYMENT FLOW (one transaction):
 *   payments/{payKey} + order.paidCents/status + receipt counter++ + printJobs/rcpt_{payKey} (1 copy)
 *
 * - `payKey` is generated by the cashier screen once per confirm; a double tap returns the same payment,
 *   so a receipt can never print twice by accident.
 * - The receipt print job is created ONLY here, i.e. only after payment is confirmed.
 * - Totals are recalculated from the order inside the transaction (not taken from the screen).
 */
export interface ConfirmPaymentInput {
  payKey: string;
  orderId: string;
  method: PaymentMethod;
  /** Part of the bill to settle now (before rounding). Use the full remaining amount for a normal payment. */
  amountCents: number;
  tenderedCents: number;
  staff: Staff;
  settings: Settings;
}

export async function confirmPayment(input: ConfirmPaymentInput): Promise<Payment> {
  const { payKey, orderId, method, staff, settings } = input;
  let result: Payment | null = null;

  await runTransaction(db, async (tx) => {
    const payRef = docRef(COL.payments, payKey);
    const orderRef = docRef(COL.orders, orderId);
    const counterRef = docRef(COL.counters, 'receipts');
    const [paySnap, orderSnap, counterSnap] = await Promise.all([tx.get(payRef), tx.get(orderRef), tx.get(counterRef)]);

    if (paySnap.exists()) {
      result = fromSnap<Payment>(paySnap); // double tap — already done
      return;
    }
    if (!orderSnap.exists()) throw new AppError('ORDER_NOT_FOUND');
    const order = fromSnap<Order>(orderSnap);
    if (order.status === 'paid' || order.status === 'cancelled') throw new AppError('ORDER_CLOSED');

    const totals = computeTotals({
      lines: order.lines,
      tax: settings.tax,
      orderType: order.type,
      discountPercent: order.discountPercent,
    });
    const remaining = totals.beforeRoundingCents - order.paidCents;
    const amount = Math.min(Math.max(0, input.amountCents), remaining);
    const settles = amount === remaining;
    const rounding =
      settles && method.kind === 'cash' && settings.tax.cashRounding ? roundTo5Sen(amount) - amount : 0;
    const charged = amount + rounding;
    const tendered = method.kind === 'cash' ? input.tenderedCents : charged;
    if (tendered < charged) throw new AppError('PAYMENT_SHORT');

    const now = Date.now();
    const next = (counterSnap.exists() ? (counterSnap.data().value as number) : 0) + 1;
    const payment: Payment = {
      id: payKey,
      orderId,
      orderNumber: order.number,
      tableLabel: order.tableLabel,
      receiptNo: `RCP-${ymd(now)}-${String(next).padStart(4, '0')}`,
      methodId: method.id,
      methodLabel: method.label,
      methodKind: method.kind,
      amountCents: amount,
      roundingCents: rounding,
      chargedCents: charged,
      tenderedCents: tendered,
      changeCents: tendered - charged,
      settlesOrder: settles,
      totals: { ...totals, roundingCents: rounding, totalCents: totals.beforeRoundingCents + rounding },
      cashierId: staff.id,
      cashierName: staff.name,
      createdAt: now,
    };

    // eslint-disable-next-line @typescript-eslint/no-unused-vars
    const { id: _omit, ...paymentData } = payment;
    tx.set(payRef, paymentData);
    tx.set(counterRef, { value: next });
    tx.update(orderRef, {
      paidCents: order.paidCents + amount,
      status: settles ? 'paid' : order.status,
      paidAt: settles ? now : null,
      updatedAt: now,
    });

    if (settings.printing.autoPrintReceipt) {
      const job: Omit<PrintJob, 'id'> = {
        type: 'receipt',
        ref: payment.receiptNo,
        summary: `${order.number} · ${order.tableLabel} · ${method.label}`,
        pages: buildReceiptPages({ settings, order, payment }),
        paperWidth: settings.receipt.paperWidth,
        status: 'pending',
        attempts: 0,
        error: null,
        createdBy: staff.name,
        createdAt: now,
        updatedAt: now,
      };
      tx.set(docRef(COL.printJobs, `rcpt_${payKey}`), job);
    }
    result = payment;
  });

  if (!result) throw new AppError('UNKNOWN', 'payment result missing');
  const done = result as Payment;
  log.info('payments', 'payment confirmed', { receipt: done.receiptNo, order: done.orderNumber });
  await writeAudit(staff, 'payment.confirm', {
    receiptNo: done.receiptNo,
    orderNumber: done.orderNumber,
    chargedCents: done.chargedCents,
    method: done.methodLabel,
  });
  return done;
}
